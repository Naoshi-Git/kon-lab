function makeTrip(prefix, direction, row, stopIds) {
  const [number, ...times] = row;
  return {
    id: `${prefix}${String(number).padStart(2, "0")}`,
    number,
    direction,
    stops: stopIds.flatMap((stopId, index) =>
      times[index] ? [{ stopId, time: times[index] }] : []
    )
  };
}

